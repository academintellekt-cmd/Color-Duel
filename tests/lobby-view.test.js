const assert=require('assert');
global.LobbyOptions=require('../lib/lobby-options');
const L=require('../public/lobby');
const names={modes:{combination:'ЦВЕТОВАЯ КОМБИНАЦИЯ',rhythm:'РИТМ-ДУЭЛЬ',pingPong:'ПИНГ-ПОНГ',colorRing:'ЦВЕТОВОЕ КОЛЬЦО'},difficulties:{easy:'ЛЁГКИЙ',medium:'СРЕДНИЙ',hard:'СЛОЖНЫЙ',extreme:'ЭКСТРИМ'},minute:'МИН'};
function view(extra){const selection=extra.selection||LobbyOptions.defaultSelection('combination',[1,2,3,4]);const players=extra.players||[];const session=!!extra.session;return{lang:'ru',players,max:2,selection,options:LobbyOptions.modeOptions(selection.mode,[1,2,3,4]),names,check:LobbyOptions.canStart(selection,players,2,session),session,remainingSec:0,connected:true,overlay:null,rules:null,starting:false,startDenied:'',languageHtml:'<div class="language-widget">LANG</div>',...extra}}
let html=L.html(view({}));
assert(html.includes('class="lobby-screen'));
assert(html.includes('COLOR DUEL'));
assert.strictEqual((html.match(/data-lobby-mode="/g)||[]).length,4,'four modes');
assert.strictEqual((html.match(/class="lobby-slot empty/g)||[]).length,2);
assert(html.includes('VS'));
assert(/data-lobby-start[^>]*disabled/.test(html),'start disabled with no players');
assert(html.includes('Для дуэли нужны два игрока'));
assert(html.includes('LANG'),'language widget in header');
assert.strictEqual((html.match(/data-lobby-difficulty="/g)||[]).length,4,'combination has 4 difficulties');
assert(html.includes('data-lobby-duration="1"')&&html.includes('data-lobby-duration="3"'));
const two=[{uid:'A',name:'Ann',avatar:'X3'},{uid:'B',name:'<b>Bob</b>',avatar:null}];
html=L.html(view({players:two}));
assert(!/data-lobby-start[^>]*disabled/.test(html));
assert(html.includes('data-lobby-remove="A"'));
assert(html.includes('&lt;b&gt;Bob&lt;/b&gt;'));
assert(html.includes('hex-cyan'),'X3 avatar is the cyan diamond');
assert(html.includes('hex-orange'),'slot 2 without avatar is orange');
html=L.html(view({players:two,selection:{mode:'colorRing',variant:null,difficulty:'hard',durationMinutes:2}}));
assert.strictEqual((html.match(/data-lobby-difficulty="/g)||[]).length,3);
assert(html.includes('ЦВЕТОВОЕ КОЛЬЦО · СЛОЖНЫЙ · 2 МИН'));
html=L.html(view({players:two,session:true,remainingSec:125}));
assert(!html.includes('data-lobby-remove'));
assert(html.includes('data-action="end"')&&html.includes('Завершить'));
assert(html.includes('data-action="leaders"'),'Records opens the leaderboard during a session');
assert(html.includes('2:05'));
assert(!/data-lobby-start[^>]*disabled/.test(html),'session start is enabled');
html=L.html(view({overlay:{type:'denied',reason:'offline'}}));
assert(html.includes('Нет связи с сервером'));
html=L.html(view({overlay:{type:'checking'}}));
assert(html.includes('Проверяем браслет'));
html=L.html(view({overlay:{type:'rules',mode:'rhythm'},rules:{title:'РИТМ-ДУЭЛЬ',lead:'Попадай в цвет и ритм',steps:['шаг 1','шаг 2'],demoHtml:''}}));
assert(html.includes('Как играть')&&html.includes('Попадай в цвет и ритм')&&html.includes('<li>шаг 2</li>')&&html.includes('Понятно'));
html=L.html(view({overlay:{type:'idle'}}));
assert(html.includes('Вы ещё здесь?')&&html.includes('data-lobby-idle="no"'));
html=L.html(view({players:two,overlay:{type:'confirmRemove',uid:'A'}}));
assert(html.includes('Убрать игрока?')&&html.includes('data-lobby-confirm="yes"'));
html=L.html(view({connected:false}));
assert(html.includes('Нет связи с Gateway'));
html=L.html(view({players:two,startDenied:'not_enough_players'}));
assert(html.includes('Ждём второго игрока'));
for(const lang of['ru','en','de','fr','zh','ja']){const s=L.strings(lang);for(const key of Object.keys(L.strings('en')))assert(s[key],`${lang}.${key}`)}
assert.strictEqual(L.enterHtml('ru'),'<div class="lobby-enter" data-lobby-enter role="status"><b>Входите</b></div>','enter call markup');
assert(L.enterHtml('en').includes('Come in'),'enter call is localized');
html=L.html(view({overlay:{type:'denied',reason:'unregistered'}}));
assert(html.includes('Данный браслет не найден в системе. Обратитесь к администратору.'),'Lava Jump wording for an unknown wristband');
html=L.html(view({session:true}));
assert(html.includes('data-action="leaders"')&&html.includes('Рекорды'),'session shows Records next to Finish');
// Lobby profile window.
const duo=[{uid:'A',name:'Алекс',avatar:'X1'},{uid:'B',name:'Мира',avatar:'X2'}];
html=L.html(view({players:duo}));
assert(html.includes('data-lobby-profile="A"')&&html.includes('data-lobby-profile="B"'),'player cards open the profile');
const data={username:'Алекс',level:2,xp_in_level:60,needed_xp:400,time_started:false,remaining_seconds:300,records:[{mode_id:'rhythm',level_id:'extreme:3',best_score:57}],recent:[]};
html=L.html(view({players:duo,overlay:{type:'profile',uid:'A',state:'ready',data}}));
assert(html.includes('Уровень 2')&&html.includes('5:00')&&html.includes('время пойдёт с первой игры'),'level and not-started time');
assert(html.includes('РИТМ-ДУЭЛЬ · ЭКСТРИМ · 3 МИН'),'records name mode, difficulty and time');
html=L.html(view({players:duo,session:true,overlay:{type:'profile',uid:'A',state:'loading'}}));
assert(html.includes('Загружаем профиль')&&!html.includes('data-lobby-profile-remove'),'loading; no removing during a paid session');
console.log('lobby-view tests passed');
